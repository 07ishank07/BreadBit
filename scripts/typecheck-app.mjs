import ts from 'typescript';
import path from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
const root = path.resolve(import.meta.dirname, '..');
process.chdir(root);
const configPath = path.join(root, 'apps/desktop/tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configPath));
const program = ts.createProgram(parsed.fileNames, parsed.options);
const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
const vendor = path.join(root, 'vendor') + path.sep;
const baseline = diagnostics.filter(d => d.file && path.resolve(d.file.fileName).startsWith(vendor));
const authored = diagnostics.filter(d => !baseline.includes(d));
const host = { getCanonicalFileName: p => p, getCurrentDirectory: () => root, getNewLine: () => '\n' };
mkdirSync(path.join(root, '.cache'), { recursive: true });
writeFileSync(path.join(root, '.cache/upstream-typecheck.txt'), ts.formatDiagnostics(baseline, host));
if (baseline.length) console.warn(`Pinned upstream has ${baseline.length} TypeScript diagnostics; see .cache/upstream-typecheck.txt. These are NOT a clean upstream typecheck.`);
if (authored.length) console.error(ts.formatDiagnostics(authored, host));
else console.log('BreadBit app and adapter TypeScript checks passed.');
process.exitCode = authored.length ? 1 : 0;
